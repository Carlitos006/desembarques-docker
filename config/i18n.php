function translate(string $key, array $replacements = [], ?string $language = null): string
{
    $language = $language !== null ? normalizeLanguage($language) : getAppLanguage();
    $translations = appTranslations();

    $value = $translations[$language][$key] ?? $translations['es'][$key] ?? $key;

    if ($replacements !== []) {
        $replacePairs = [];

        foreach ($replacements as $placeholder => $replacement) {
            $replacePairs['{{' . $placeholder . '}}'] = (string) $replacement;
        }

        $value = strtr($value, $replacePairs);
    }

    return $value;
}

/**
 * Returns a short bilingual string without requiring a catalogue key.
 *
 * Use this for endpoint-specific validation and operational messages. Stable UI
 * labels should continue using translate() so they remain centrally searchable.
 */
function translateText(string $spanish, string $english, ?string $language = null): string
{
    $language = $language !== null ? normalizeLanguage($language) : getAppLanguage();

    return $language === 'en' ? $english : $spanish;
}

function translateRoleLabel(string $role, ?string $language = null): string
{
    $translation = translate('roles.' . $role, [], $language);

    return $translation === 'roles.' . $role ? ucfirst($role) : $translation;
}

function getSupportedLanguages(?string $language = null): array
{
    $language = $language !== null ? normalizeLanguage($language) : getAppLanguage();
    $languages = [];

    foreach (APP_SUPPORTED_LANGUAGES as $code) {
        $languages[$code] = [
            'code' => $code,
            'label' => translate('app.language.' . $code, [], $language),
        ];
    }

    return $languages;
}

function getClientTranslations(array $keys, ?string $language = null): array
{
    $language = $language !== null ? normalizeLanguage($language) : getAppLanguage();
    $translations = appTranslations();
    $result = [];

    foreach ($keys as $key) {
        $result[$key] = $translations[$language][$key] ?? $translations['es'][$key] ?? $key;
    }

    return $result;
}
