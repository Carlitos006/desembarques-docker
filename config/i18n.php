const APP_SUPPORTED_LANGUAGES = ['es', 'en'];

function normalizeLanguage(?string $language): string
{
    $language = strtolower((string) $language);

    return in_array($language, APP_SUPPORTED_LANGUAGES, true) ? $language : 'es';
}

function setAppLanguage(?string $language): void
{
    $_SESSION['language'] = normalizeLanguage($language);
}

function getAppLanguage(): string
{
    return normalizeLanguage($_SESSION['language'] ?? 'es');
}

